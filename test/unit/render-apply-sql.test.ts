import { describe, expect, it } from 'vitest'
import { BRAND } from '../../src/brand.ts'
import { renderApplySql } from '../../src/render/apply-sql.ts'
import { config, orders, users } from '../helpers/views.ts'

describe('apply SQL', () => {
  const sql = renderApplySql({ config, views: [users, orders] })

  it('is generated by the product and marks the schema it creates', () => {
    expect(sql.split('\n')[0]).toBe(
      `-- GENERATED by ${BRAND} from schema.prisma. Do not edit by hand.`,
    )
    expect(sql).toContain(
      `COMMENT ON SCHEMA "ai" IS 'Generated by ${BRAND}. Read-only, PII-filtered views`,
    )
  })

  it('runs as one transaction and creates the role only when missing', () => {
    expect(sql).toContain('SET client_min_messages = warning;\nBEGIN;\n')
    expect(sql).toContain("IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ai_reader') THEN")
    expect(sql).toContain('CREATE ROLE "ai_reader" NOLOGIN;')
    expect(sql.trimEnd().endsWith('COMMIT;')).toBe(true)
  })

  it('creates one view per input with exactly its columns, quoting identifiers', () => {
    expect(sql).toContain(
      'CREATE VIEW "ai"."users" AS SELECT\n  "id",\n  "country"\nFROM "public"."users";',
    )
    expect(sql).toContain(
      'CREATE VIEW "ai"."orders" AS SELECT\n  "id",\n  "user_id"\nFROM "sales"."Order Items";',
    )
  })

  it('escapes doc comments as string literals', () => {
    expect(sql).toContain(`COMMENT ON VIEW "ai"."users" IS 'A customer''s account.';`)
    expect(sql).toContain(`COMMENT ON COLUMN "ai"."users"."country" IS 'ISO | code';`)
    expect(sql).not.toContain('COMMENT ON VIEW "ai"."orders"')
  })

  it('grants nothing but USAGE and SELECT in the AI schema and sets session defaults', () => {
    expect(sql).toContain('REVOKE ALL ON SCHEMA "public" FROM "ai_reader";')
    expect(sql).toContain('GRANT USAGE ON SCHEMA "ai" TO "ai_reader";')
    expect(sql).toContain('GRANT SELECT ON ALL TABLES IN SCHEMA "ai" TO "ai_reader";')
    expect(sql).toContain('ALTER ROLE "ai_reader" SET default_transaction_read_only = on;')
    expect(sql).toContain(`ALTER ROLE "ai_reader" SET statement_timeout = '15s';`)
    expect(sql).toContain('ALTER ROLE "ai_reader" SET search_path = "ai";')
  })

  it('keeps the base leak and membership checks', () => {
    expect(sql).toContain("WHERE c.relkind IN ('r', 'p', 'v', 'm', 'f')")
    expect(sql).toContain(
      `RAISE EXCEPTION '${BRAND}: role ai_reader can read relations outside schema ai: %', leaks;`,
    )
    expect(sql).toContain(
      `RAISE EXCEPTION '${BRAND}: role ai_reader must not be a member of other roles';`,
    )
  })

  it('D54: is branded hyde-db', () => {
    expect(sql.split('\n')[0]).toBe(
      '-- GENERATED by hyde-db from schema.prisma. Do not edit by hand.',
    )
    expect(sql).toContain(
      `COMMENT ON SCHEMA "ai" IS 'Generated by hyde-db. Read-only, PII-filtered views for AI/LLM access. Recreated on every deploy.';`,
    )
    expect(sql).not.toContain('prisma-ai-views')
  })

  it('D11: guards the DROP SCHEMA with the marker check', () => {
    const guard = sql.indexOf("IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'ai'")
    expect(guard).toBeGreaterThan(0)
    expect(guard).toBeLessThan(sql.indexOf('DROP SCHEMA IF EXISTS "ai" CASCADE;'))
  })

  it('D58: the marker check accepts only the exact marker or the marker followed by a period', () => {
    expect(sql).toContain(
      "AND NOT (coalesce(obj_description(oid, 'pg_namespace'), '') = 'Generated by hyde-db'\n" +
        "                      OR starts_with(coalesce(obj_description(oid, 'pg_namespace'), ''), 'Generated by hyde-db.'))) THEN",
    )
    expect(sql).not.toContain("''), 'Generated by hyde-db')")
  })

  it('D11: the marker guard checks the configured schema', () => {
    const custom = renderApplySql({ config: { ...config, schema: 'llm' }, views: [] })
    expect(custom).toContain("IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'llm'")
    expect(custom).toContain('hyde-db: schema llm exists but was not created by hyde-db')
    expect(custom).not.toContain("'ai'")
  })

  it('D13: aborts on executable SECURITY DEFINER functions and readable sequences', () => {
    expect(sql).toContain('    AND p.prosecdef')
    expect(sql).toContain('REVOKE EXECUTE ON ROUTINE %s FROM %s;')
    expect(sql).toContain(
      "CASE WHEN c.relkind = 'S' THEN has_sequence_privilege(r.oid, c.oid, 'SELECT, USAGE, UPDATE') ELSE false END",
    )
    expect(sql).toContain('REVOKE ALL ON SEQUENCE %s FROM %s;')
  })

  it('D13: names the role in the fix when it owns the function or sequence', () => {
    expect(sql).toContain('r.oid = p.proowner')
    expect(sql).toContain('r.oid = c.relowner')
  })

  it('uses the configured schema, role and timeout everywhere', () => {
    const custom = renderApplySql({
      config: {
        ...config,
        schema: 'llm',
        role: 'llm_reader',
        sourceSchema: 'app',
        statementTimeout: '5s',
      },
      views: [],
    })
    expect(custom).toContain('CREATE SCHEMA "llm";')
    expect(custom).toContain('REVOKE ALL ON SCHEMA "app" FROM "llm_reader";')
    expect(custom).toContain(`ALTER ROLE "llm_reader" SET statement_timeout = '5s';`)
    expect(custom).not.toMatch(/"ai"|ai_reader/)
  })
})
